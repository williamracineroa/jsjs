// numerical operators 

let n1 = 10
let n2 = 20

console.log(n2 - n1) // substract
console.log(n2 + n1) // sum
console.log(n2 * n1) // multiply
console.log(n2 / n1) // division
console.log(n2 % n1) // modulo or remainder of the division
console.log(n2 ** n1) // power

n1++ // increment by 1
n2-- // decrement by 1


// comparation operators 

console.log(5 == "5") // compare only valor
console.log(5 === "5") // compare valor and type, in this case is comparing type string with number 
console.log(6 < 8)
console.log(6 > 8)
console.log(6 <= 8)
console.log(6 >= 8)

// logics operators

let age = 21

console.log(age > 18 && age < 30) // && : " and " 
console.log(age > 18 || age > 30) // || : " or " 
console.log(!(age > 18)) // ! : " not "

